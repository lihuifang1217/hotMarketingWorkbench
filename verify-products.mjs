import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const context=vm.createContext({globalThis:{}});
for(const path of ['src/data.js','src/catalog.js','src/matching.js'])vm.runInContext(fs.readFileSync(path,'utf8'),context,{filename:path});
const {defaultProducts}=context.globalThis.HotData;
const catalog=context.globalThis.HotCatalog;
const stats=catalog.summary(defaultProducts);
assert.equal(stats.total,9);
assert.equal(stats.categories,6);
assert.equal(stats.min,39);
assert.equal(stats.max,269);
assert.equal(stats.discountCount,9);
assert.equal((stats.averageDiscount*100).toFixed(1),'22.2');
assert.deepEqual(Array.from(catalog.filterSort(defaultProducts,{query:'缓震'}),p=>p.id),['p3']);
assert.deepEqual(Array.from(catalog.filterSort(defaultProducts,{category:'运动',sort:'price-asc'}),p=>p.price),[39,239,269]);
assert.deepEqual(Array.from(catalog.filterSort(defaultProducts,{sort:'price-desc'}).slice(0,2),p=>p.price),[269,239]);
const firstPage=catalog.paginate(defaultProducts,{page:1,pageSize:5});
const lastPage=catalog.paginate(defaultProducts,{page:2,pageSize:5});
assert.equal(firstPage.items.length,5);
assert.equal(lastPage.items.length,4);
assert.equal(lastPage.pages,2);
assert.equal(lastPage.start,6);
assert.equal(lastPage.end,9);
assert.equal(new Set([...firstPage.items,...lastPage.items].map(item=>item.id)).size,9);
assert.equal(catalog.paginate(defaultProducts,{page:99,pageSize:5}).page,2);
assert.equal(catalog.paginate(catalog.filterSort(defaultProducts,{query:'缓震'}),{page:2,pageSize:5}).page,1);
assert.equal(catalog.paginate([],{page:2,pageSize:5}).start,0);
assert.equal(catalog.paginate([],{page:2,pageSize:5}).pages,1);
assert.equal(catalog.paginate(defaultProducts,{pageSize:20}).items.length,9);
assert.equal(catalog.summary([{id:'x',name:'测试',category:'自定义',price:10}]).averageDiscount,null);
assert.equal(catalog.nextId(defaultProducts),'p10');
const sample={id:'p10',name:'夜跑反光运动臂包',emoji:'🎧',color:'#ede9fe',price:89,originalPrice:139,category:'运动',selling:'夜跑时随身收纳，反光设计更醒目',tags:['夜跑','运动','反光']};
const copied=catalog.copyProduct({...sample,url:'product.html?id=p10'},[...defaultProducts,sample]);
assert.equal(copied.id,'p11');
assert.equal(copied.name,'夜跑反光运动臂包（副本）');
assert.equal(copied.url,'product.html?id=p11');
copied.tags.push('新增标签');
assert.equal(sample.tags.length,3);
assert.equal(catalog.copyProduct({...sample,url:'https://example.com/product'},defaultProducts).url,'https://example.com/product');
assert.equal(Object.keys(catalog.validateProduct(copied,{products:[...defaultProducts,sample]})).length,0);
assert.equal(Object.keys(catalog.validateProduct(sample,{products:defaultProducts})).length,0);
assert.equal(catalog.validateProduct({...sample,originalPrice:59},{products:defaultProducts}).originalPrice,'原价不能低于售价');
assert.equal(catalog.validateProduct({...sample,name:''},{products:defaultProducts}).name,'请输入商品名称');
assert.equal(catalog.validateProduct({...sample,id:'p1'},{products:defaultProducts}).id,'商品编号已存在，请重新生成');
assert.ok(context.globalThis.HotData.productImage({...sample,artMode:'emoji'}).startsWith('data:image/svg+xml,'));
const news={title:'城市夜跑持续升温，年轻人解锁运动新方式',risk:{level:'safe'}};
assert.ok(context.globalThis.HotMatching.matchProducts(news,[sample]).some(item=>item.product.id==='p10'));
const referenceNews=context.globalThis.HotData.normalizeNews(context.globalThis.HotData.demoNews);
const references=catalog.recommendationReferences(referenceNews,[...defaultProducts,sample],context.globalThis.HotMatching.matchProducts);
assert.equal(references.get('p10').length,1);
assert.equal(references.get('p10')[0],news.title);
const changed=catalog.bulkChange([...defaultProducts,sample],new Set(['p8','p10']),{type:'category',category:'运动配件'});
assert.equal(changed.success,2);
assert.equal(catalog.summary(changed.products).categories,7);
assert.equal(changed.products.find(item=>item.id==='p10').category,'运动配件');
const removed=catalog.bulkChange(changed.products,new Set(['p10','missing']),{type:'delete'});
assert.equal(removed.success,1);
assert.equal(removed.skipped[0].reason,'商品已不存在');
assert.ok(!context.globalThis.HotMatching.matchProducts(news,removed.products).some(item=>item.product.id==='p10'));
const protectedResult=catalog.bulkChange(defaultProducts,new Set(defaultProducts.map(item=>item.id)),{type:'delete'});
assert.equal(protectedResult.success,0);
assert.equal(protectedResult.skipped.length,9);
const injected={id:'x',name:'<script>alert(1)</script>',category:'<img src=x>',selling:'" onmouseover="alert(1)',tags:['<b>'],price:10,color:'red;position:fixed'};
const markup=catalog.renderCard(injected);
assert.ok(markup.includes('&lt;script&gt;'));
assert.ok(!markup.includes('<script>'));
assert.ok(!markup.includes('position:fixed'));
assert.ok(markup.includes('product-price-stack'));
console.log('商品库规则验证通过：统计、搜索、筛选、排序、分页与页码修正、编号与字段校验、引用计数、批量品类、批量删除、匹配更新、内容转义');
