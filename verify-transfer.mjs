import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const context=vm.createContext({globalThis:{}});
for(const file of ['src/data.js','src/catalog.js','src/product-transfer.js'])vm.runInContext(fs.readFileSync(file,'utf8'),context,{filename:file});
const transfer=context.globalThis.HotProductTransfer;
const products=JSON.parse(fs.readFileSync('data/config.json','utf8')).products;
const plain=value=>JSON.parse(JSON.stringify(value));
const json=transfer.importJson(transfer.exportJson(products));
assert.deepEqual(plain(json.errors),[]);
assert.deepEqual(plain(json.products),products);
const csv=transfer.importCsv(transfer.exportCsv(products));
assert.deepEqual(plain(csv.errors),[]);
assert.deepEqual(plain(csv.products),products);
const legacy={...context.globalThis.HotData.defaultProducts[1]};
delete legacy.originalPrice;
const legacyCsv=transfer.exportCsv([legacy]);
assert.deepEqual(plain(transfer.importCsv(legacyCsv).products),plain([legacy]));
const changedLegacy=transfer.importCsv(legacyCsv.replace('"89"','"90"'));
assert.equal(changedLegacy.products[0].price,90);
assert.equal(changedLegacy.products[0].originalPrice,119);
const sixColumns=transfer.importCsv('名称,售价,原价,品类,卖点,图标\n"轻便,出游包",59,79,户外,便携、露营,🎒\n');
assert.deepEqual(plain(sixColumns.errors),[]);
assert.equal(sixColumns.products[0].name,'轻便,出游包');
assert.equal(sixColumns.products[0].id,'p1');
assert.equal(sixColumns.products[0].color,'#dbeafe');
const special={...products[0],id:'special',name:'轻便,「出游」外套',selling:'适合"通勤",周末\n也能穿',tags:['凉感,透气','防晒']};
const quoted=transfer.importCsv(transfer.exportCsv([special]));
assert.deepEqual(plain(quoted.errors),[]);
assert.deepEqual(plain(quoted.products),[special]);
const bad=transfer.exportCsv(products).replace('"129"','"-1"');
const invalid=transfer.importCsv(bad);
assert.ok(invalid.errors.some(item=>item.line===2&&item.reason.includes('售价')));
assert.equal(transfer.importCsv('名称,售价,原价,品类,卖点,图标\n"缺价格",-2,30,穿搭,轻薄,🧥\n').errors[0].line,2);
assert.ok(transfer.importCsv('名称,售价,原价,品类,卖点,图标\n"坏引号,1,2,穿搭,轻薄,🧥').errors[0].reason.includes('引号'));
assert.ok(transfer.importJson('{oops').errors[0].reason.includes('JSON'));
const formula={...products[0],id:'formula',name:'=SUM(1,2)'};
assert.deepEqual(plain(transfer.importCsv(transfer.exportCsv([formula])).products),[formula]);
console.log(`商品导入导出验证通过：${products.length} 件商品 JSON/CSV 原样回导、六列表格、引号/逗号/换行、公式前缀、负价格行号、坏格式`);
